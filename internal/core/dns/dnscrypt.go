package dns

import (
	"context"
	"errors"
	"fmt"
	"log"
	"net"

	dnscryptlib "github.com/ameshkov/dnscrypt/v2"
	"github.com/miekg/dns"
)

// defaultDNSCryptPort avoids 443/TCP, which is the SNI proxy's listener. DNSCrypt
// uses the same port for UDP and TCP, so a separate default is the only way to
// keep both transports available without a silent conflict.
const defaultDNSCryptPort = 5443

// dnscryptBridge adapts DigitDNS's resolver to the DNSCrypt server handler. The// library has already authenticated and decrypted the query by the time this is
// called; the ordinary access gate, rules and cache run exactly as they do for
// every other transport.
type dnscryptBridge struct {
	s *Server
}

func (b *dnscryptBridge) ServeDNS(rw dnscryptlib.ResponseWriter, req *dns.Msg) error {
	clientIP := rw.RemoteAddr().String()
	if host, _, err := net.SplitHostPort(clientIP); err == nil {
		clientIP = host
	}
	resp := b.s.handler.ProcessQuery(req, clientIP, "DNSCrypt", clientIP)
	if resp == nil {
		b.s.dnscryptErrors.Add(1)
		return errors.New("resolver returned no response")
	}
	if err := rw.WriteMsg(resp); err != nil {
		b.s.dnscryptErrors.Add(1)
		return err
	}
	b.s.dnscryptQueries.Add(1)
	return nil
}

// SetDNSCryptConfig installs the provider/resolver keys generated by the web
// layer. A running listener is stopped so the next ApplyTransports restarts it
// with the new identity; stamps and certificates change with those keys.
func (s *Server) SetDNSCryptConfig(rc *dnscryptlib.ResolverConfig, cert *dnscryptlib.Cert) {
	s.tlsMu.Lock()
	defer s.tlsMu.Unlock()
	s.dnscryptRC = rc
	s.dnscryptCert = cert
	if s.dnscryptServer != nil {
		s.stopDNSCryptLocked()
	}
	s.clearDNSCryptError()
}

// DNSCryptStatus reports whether the listener is actually serving and when its
// current certificate expires.
func (s *Server) DNSCryptStatus() (listening bool, certNotAfter int64, listenerErr string) {
	s.tlsMu.Lock()
	listening = s.dnscryptListening.Load()
	s.tlsMu.Unlock()
	if s.dnscryptCert != nil {
		certNotAfter = int64(s.dnscryptCert.NotAfter)
	}
	s.listenerErrMu.Lock()
	listenerErr = s.dnscryptErr
	s.listenerErrMu.Unlock()
	return listening, certNotAfter, listenerErr
}

func (s *Server) setDNSCryptError(msg string) {
	s.listenerErrMu.Lock()
	s.dnscryptErr = msg
	s.listenerErrMu.Unlock()
}

func (s *Server) clearDNSCryptError() {
	s.setDNSCryptError("")
}

// startDNSCryptLocked binds UDP and TCP on the same port. The caller holds
// tlsMu or is Start before any listener serves.
func (s *Server) startDNSCryptLocked() error {
	if !s.transportCfg.DNSCryptEnabled || s.dnscryptServer != nil {
		return nil
	}
	if s.dnscryptRC == nil || s.dnscryptCert == nil {
		err := errors.New("DNSCrypt requires generated provider keys")
		s.setDNSCryptError(err.Error())
		return err
	}
	port := s.transportCfg.DNSCryptPort
	if port == 0 {
		port = defaultDNSCryptPort
	}
	addr := s.addr(port)

	udpAddr, err := net.ResolveUDPAddr("udp", addr)
	if err != nil {
		err = fmt.Errorf("resolve DNSCrypt UDP %s: %w", addr, err)
		s.setDNSCryptError(err.Error())
		return err
	}
	udpConn, err := net.ListenUDP("udp", udpAddr)
	if err != nil {
		err = fmt.Errorf("bind DNSCrypt UDP %s: %w", addr, err)
		s.setDNSCryptError(err.Error())
		return err
	}
	tcpLn, err := net.Listen("tcp", addr)
	if err != nil {
		_ = udpConn.Close()
		err = fmt.Errorf("bind DNSCrypt TCP %s: %w", addr, err)
		s.setDNSCryptError(err.Error())
		return err
	}

	srv := &dnscryptlib.Server{
		ProviderName: s.dnscryptRC.ProviderName,
		ResolverCert: s.dnscryptCert,
		Handler:      &dnscryptBridge{s: s},
	}
	s.dnscryptServer = srv
	s.dnscryptUDP = udpConn
	s.dnscryptTCP = tcpLn
	s.dnscryptListening.Store(true)
	s.clearDNSCryptError()

	go func() {
		if err := srv.ServeUDP(udpConn); err != nil {
			s.dnscryptStopped(srv, "DNSCrypt UDP listener stopped: "+err.Error())
		}
	}()
	go func() {
		if err := srv.ServeTCP(tcpLn); err != nil {
			s.dnscryptStopped(srv, "DNSCrypt TCP listener stopped: "+err.Error())
		}
	}()
	log.Printf("[DNS] Starting DNSCrypt on udp+tcp://%s", addr)
	return nil
}

func (s *Server) dnscryptStopped(srv *dnscryptlib.Server, reason string) {
	s.tlsMu.Lock()
	current := s.dnscryptServer == srv
	if current {
		s.dnscryptServer = nil
		s.dnscryptUDP = nil
		s.dnscryptTCP = nil
		s.dnscryptListening.Store(false)
		s.setDNSCryptError(reason)
	}
	s.tlsMu.Unlock()
	if current {
		log.Printf("[DNS] %s", reason)
	}
}

// stopDNSCryptLocked closes both listeners. The caller holds tlsMu. Shutdown is
// started off the lock: the library waits for its serve goroutines, and those
// goroutines report a listener failure by taking tlsMu themselves, so waiting
// here would deadlock until the shutdown grace expires.
func (s *Server) stopDNSCryptLocked() {
	s.dnscryptListening.Store(false)
	srv := s.dnscryptServer
	udpConn := s.dnscryptUDP
	tcpLn := s.dnscryptTCP
	s.dnscryptServer = nil
	s.dnscryptUDP = nil
	s.dnscryptTCP = nil
	if srv != nil {
		go func() {
			ctx, cancel := context.WithTimeout(context.Background(), shutdownGrace)
			defer cancel()
			_ = srv.Shutdown(ctx)
		}()
	}
	if udpConn != nil {
		_ = udpConn.Close()
	}
	if tcpLn != nil {
		_ = tcpLn.Close()
	}
	s.clearDNSCryptError()
}
